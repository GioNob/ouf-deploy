def prepare_file_only_installation(*,engine,selection,package_directory,semantic_record,image_audit,postgres,
        producer_observations,cohort_plan,owner_mount,proposal_key,proposal_identity,source_closure_hash,
        authority_directory,command_binding,frame_inputs=None,source_directory=None,iam_profile=None):
    """One collector call; returned private data is not a signed mandate.

    frame_inputs binds the fixed independent baseline, original consultation key,
    reviewed runtime/network configuration and package rootfs seal. Template and
    launch are compiled here, never copied from the replacement OCI.
    """
    require(type(engine) is Engine and hash_value(source_closure_hash),'REAL_REGISTRY_PREPARATION_ENGINE_REQUIRED')
    native_commands(command_binding,engine)
    values,retirement=retained_inputs(selection);declaration=values['declaration'];review=values['installationReview']
    cid=review['currentRegistry']['id'];code,actual=engine.request('GET','/v1.44/containers/'+cid+'/json')
    require(code==200 and actual['Id']==cid and actual['Image']==review['currentRegistry']['image']
            and actual['State']['Pid']==review['currentRegistry']['pid'] and actual['State']['StartedAt']==review['currentRegistry']['startedAt']
            and actual['State']['Running'] is True,'CURRENT_RETAINED_REGISTRY_REQUIRED')
    code,pg=engine.request('GET','/v1.44/containers/'+postgres['Id']+'/json');require(code==200 and Engine.runtime_binding(pg)==Engine.runtime_binding(postgres),'CURRENT_SELECTED_POSTGRES_REQUIRED')
    tree=configtree(declaration);proposal=proposal_mount(proposal_key)
    seal=packaged_seal(package_directory,semantic_record)
    if frame_inputs is None:
        require(source_directory is not None and type(iam_profile) is dict,'COMPLETE_GROUPED_FRAME_SOURCE_AND_IAM_INPUTS_REQUIRED')
        frame_inputs=collect_frame_inputs(selection=selection,values=values,current=actual,
            source_directory=source_directory,iam_profile=iam_profile,rootfs_limits=seal['limits'])
    require(type(frame_inputs) is dict and set(frame_inputs)=={'baselineBinding','delegationKey','dockerContext','runtimeRoot','observationConfiguration','frameSourceBinding'},
            'COMPLETE_INDEPENDENT_NATIVE_FRAME_INPUTS_REQUIRED')
    delegation=frame_inputs['delegationKey'];delegation_metadata=file_source(delegation)
    request=creation(values['creationRequest'],declaration,actual,image_audit,tree,owner_mount,delegation,proposal,proposal_identity)
    profile=FileOnlyProfile(request,tree)
    require(frame_inputs['baselineBinding']['sha256']==BASELINE_SHA256,'PINNED_INDEPENDENT_ENGINE_BASELINE_REQUIRED')
    baseline=bound(frame_inputs['baselineBinding']);code,info=engine.request('GET','/v1.44/info')
    require(code==200 and {k:info.get(v) for k,v in (('serverVersion','ServerVersion'),('storageDriver','Driver'),('cgroupDriver','CgroupDriver'))}
        =={k:FRAME_ENGINE[k] for k in ('serverVersion','storageDriver','cgroupDriver')}
        and info.get('DockerRootDir')==frame_inputs['dockerContext']['storageParent'], 'CURRENT_ENGINE_BASELINE_PROFILE_DRIFT')
    template,launch=compile_inputs(baseline,request,tree,owner_mount,delegation,proposal,FRAME_ENGINE)
    root=Path(authority_directory)/'registry';paths={'root':str(root),**{name:str(root/name) for name in DIRECTORIES}}
    require(semantic_record['module']=='semantic' and semantic_record['imageId']==image_audit['imageId']
            and semantic_record['sourceCommit']==image_audit['sourceCommit'],'ONE_REVIEWED_REGISTRY_PACKAGE_REQUIRED')
    require(frame_inputs['observationConfiguration']['rootfsLimits']==seal['limits'], 'INDEPENDENT_ROOTFS_LIMITS_DRIFT')
    migrations=packaged_migrations(package_directory,semantic_record);db=registry_database(pg,request,migrations)
    endpoints=request['NetworkingConfig']['EndpointsConfig'];require(len(endpoints)==1,'ONE_RETAINED_REGISTRY_NETWORK_REQUIRED')
    name=next(iter(endpoints));code,network=engine.request('GET','/v1.44/networks/'+endpoints[name]['NetworkID'])
    require(code==200 and network['Name']==name and network['Driver']=='bridge' and network['EnableIPv6'] is False,'CURRENT_EXACT_REGISTRY_BRIDGE_REQUIRED')
    address=endpoints[name]['IPAMConfig']['IPv4Address'];port=int(environment(request['Env']).get('PORT','8080'))
    readiness={'databaseContainerId':pg['Id'],'databaseUser':db['user'],'database':db['database'],'databaseOid':db['databaseOid'],
        'flywaySchema':'ouf_sem','flywayHistoryHash':digest(migrations),'health':{'address':address,'port':port,'path':'/actuator/health/readiness','timeoutSeconds':5}}
    recipe={'schema':'ouf.semantic-file-only-node-recipe.v1','sourceClosureHash':source_closure_hash,
        'qualifiedPackageHash':digest(semantic_record),'imageConfigurationHash':image_audit['configSha256'],
        **{k:copy.deepcopy(v) for k,v in frame_inputs.items() if k not in ('baselineBinding','delegationKey')},
        'template':template,'launch':launch,'expectedRootfsSeal':seal['rootfsSeal'],
        'renewableToken':copy.deepcopy(owner_mount),'delegationKeyMetadataHash':delegation_metadata,'proposalReceiptKey':proposal,
        'transactionId':digest({'cohortPlanHash':digest(cohort_plan),'creationRequestHash':digest(request),'directory':str(root)}),'observationSeconds':180}
    # Compile with closed synthetic identity slots only. The result is discarded;
    # no invented CID/path becomes an acceptance or a target expectation.
    context={**recipe['dockerContext'],'containerId':'a'*64,'networkNamespaceName':'b'*12,
        'rootfsPath':recipe['dockerContext']['storageParent']+'/validation-only-rootfs'}
    context.pop('rootfsLayout',None)
    compile_policy(recipe['template'],recipe['launch'],context,execution_profile=profile,renewable_token=owner_mount,
        delegation_key_metadata_hash=delegation_metadata,proposal_receipt_key=proposal)
    producers=[actual]+[p for p in producer_observations if p['Id']!=cid]
    intents=phase_intents(request,producers,network,db,pg,retirement,recipe,readiness,paths,cohort_plan)
    result={'schema':'ouf.semantic-file-only-installation-inputs.v1','creationRequest':request,'configtree':tree,'intents':intents,
        'retirementScope':retirement,'nodeRecipe':recipe,'readinessScope':readiness,'postgresRuntimeBinding':Engine.runtime_binding(pg),
        'imageAudit':copy.deepcopy(image_audit),'commandBindings':{'docker':copy.deepcopy(command_binding)},
        'directoryPlan':paths,'cohortPlanHash':digest(cohort_plan),'adminDatabase':'postgres'}
    compile_scope(result,source_closure_hash)
    for native in [*producers,pg]:
        code,fresh=engine.request('GET','/v1.44/containers/'+native['Id']+'/json')
        require(code==200 and Engine.runtime_binding(fresh)==Engine.runtime_binding(native),'REGISTRY_PREPARATION_GENERATION_CHANGED')
    require(registry_database(pg,request,migrations)==db and configtree(declaration)==tree
            and file_source(delegation)==delegation_metadata and file_source(proposal)==proposal['metadataHash'],
            'REGISTRY_PREPARATION_PRIVATE_INPUT_CHANGED')
    retained_inputs(selection);R12RetirementChannel(retirement,custody,lease_projection).current()
    return result
