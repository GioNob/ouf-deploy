def file_source(source):
    """Hash the selected mounted input privately; no bytes leave this function."""
    require(type(source) is dict and {'source','uid','gid','mode','maxBytes','sha256'}<=set(source),'EXACT_REGISTRY_MOUNT_FILE_REQUIRED')
    path=Path(source['source']);before=path.lstat()
    raw=custody.file_bytes(path,source['uid'],{source['mode']},limit=source['maxBytes'],expected=source['sha256'])
    require(before.st_gid==source['gid'] and attributes(before)==attributes(path.lstat()) and len(raw)>0,
            'REGISTRY_MOUNT_METADATA_CHANGED')
    return digest(attributes(before))

