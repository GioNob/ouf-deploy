def registry_database(postgres,request,migrations):
    env=environment(request['Env']);url=env.get('OUF_SEM_DB_URL','');require(url.startswith('jdbc:postgresql://'),'EXPLICIT_REGISTRY_DATABASE_REQUIRED')
    parsed=urlsplit(url[5:]);database=unquote(parsed.path)[1:];user=env.get('OUF_SEM_DB_USER','');identifier(database);identifier(user)
    parameters=parse_qsl(parsed.query,keep_blank_values=True,strict_parsing=True)
    require(len(parameters)<=32 and not ({key.lower() for key,_ in parameters}&
        {'user','username','password','host','hostaddr','port','dbname','database','service','servicefile'}),
        'DATABASE_URL_IDENTITY_OVERRIDE_REQUIRES_REVIEW')
    network=postgres['NetworkSettings']['Networks']['ouf-backend']
    peers={postgres['Name'].lstrip('/'),postgres['Config'].get('Hostname'),network.get('IPAddress'),*(network.get('Aliases') or [])}
    require(parsed.hostname in peers and parsed.port in (None,5432) and not parsed.fragment and not parsed.username,
            'REGISTRY_DATABASE_MUST_USE_SELECTED_POSTGRES')
    channel=Psql(postgres['Id'],user,database,'ouf-cutover-registry-observe')
    try:
        current=channel.query("SELECT json_build_object('name',current_database(),'oid',oid::bigint,'allowConnections',datallowconn,'prepared',(SELECT count(*) FROM pg_prepared_xacts WHERE database=current_database())) FROM pg_database WHERE datname=current_database()",timeout=10)
        before=channel.query("SELECT COALESCE(json_agg(json_build_object('version',version,'type',type,'script',script,'checksum',checksum,'success',success) ORDER BY installed_rank),'[]'::json) FROM ouf_sem.flyway_schema_history",timeout=10)
    finally:channel.close()
    # Preserve Flyway's exact schema-creation row, as the cohort DB planner does.
    # It is retained in expected history; no SQL file is invented for this marker.
    marker={'version':None,'type':'SCHEMA','script':'"ouf_sem"','checksum':None,'success':True}
    if before and before[0]==marker:migrations=[marker,*migrations]
    require(current.get('name')==database and type(current.get('oid')) is int and current['oid']>0
            and current.get('allowConnections') is True and current.get('prepared')==0 and type(before) is list
            and 1<=len(before)<=len(migrations)<=256 and before==migrations[:len(before)], 'CURRENT_REGISTRY_MIGRATION_PREFIX_REQUIRED')
    # The application role is not silently promoted to the fence owner. Select
    # the observed PostgreSQL bootstrap role, then prove its current native
    # privilege through the same outside-database channel used by the installer.
    admin_user=environment(postgres['Config'].get('Env') or []).get('POSTGRES_USER','')
    identifier(admin_user);require(database!='postgres','OUTSIDE_REGISTRY_ADMIN_DATABASE_REQUIRED')
    admin=Psql(postgres['Id'],admin_user,'postgres','ouf-cutover-registry-admin-review')
    try:
        role=admin.query("SELECT json_build_object('user',current_user,'database',current_database(),'superuser',rolsuper) FROM pg_roles WHERE rolname=current_user",timeout=10)
    finally:admin.close()
    require(role=={'user':admin_user,'database':'postgres','superuser':True},'CURRENT_PRIVILEGED_REGISTRY_FENCE_OWNER_REQUIRED')
    return {'database':database,'user':user,'adminUser':admin_user,'databaseOid':current['oid'],'before':before,'expected':migrations}

